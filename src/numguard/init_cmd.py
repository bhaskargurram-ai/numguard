"""``numguard init``: set a repository up in one step.

Writes small *caller* workflows that delegate to the reusable workflows in the
numguard repository, plus a commented ``numguard.toml``:

* ``.github/workflows/numguard.yml``          -- checks (``pull_request``, unprivileged)
* ``.github/workflows/numguard-comment.yml``  -- posts the card (``workflow_run``, never runs PR code)
* ``.github/workflows/numguard-agent.yml``    -- with ``--agent``: experimental suggested fixes
* ``numguard.toml``

Existing files are never overwritten unless ``force`` is set; without it
nothing is written at all, so a half-initialised repository cannot result.
``examples/workflows/`` and ``examples/numguard.toml`` in the numguard
repository are exactly what ``numguard init --agent`` writes (a test keeps
them in sync).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Sequence

from . import __version__

__all__ = ["InitError", "InitResult", "init_repo", "check_caller", "comment_caller", "agent_caller",
           "config_template", "DEFAULT_INSTALL", "TOOL_REPOSITORY"]

TOOL_REPOSITORY = "bhaskargurram-ai/numguard"
DEFAULT_REF = f"v{__version__}"
DEFAULT_INSTALL = 'pip install -e ".[dev]" || pip install -e .'
_REF_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,99}$")
_TARGET_RE = re.compile(r"^[A-Za-z0-9_./-]+:[A-Za-z_][A-Za-z0-9_.]*$")

CHECK_PATH = ".github/workflows/numguard.yml"
COMMENT_PATH = ".github/workflows/numguard-comment.yml"
AGENT_PATH = ".github/workflows/numguard-agent.yml"
CONFIG_PATH = "numguard.toml"


class InitError(RuntimeError):
    """``init`` cannot proceed (existing files, bad arguments)."""


@dataclass
class InitResult:
    written: list[str] = field(default_factory=list)
    next_steps: list[str] = field(default_factory=list)


def _yaml_str(s: str) -> str:
    return f"'{s}'" if "'" not in s else json.dumps(s)


def check_caller(ref: str, install: str = DEFAULT_INSTALL) -> str:
    prefix = f"{TOOL_REPOSITORY}/.github/workflows"
    return f"""# numguard, part 1 of 2: run the checks (UNPRIVILEGED).
#
# Runs on `pull_request`, so for pull requests from forks GitHub gives this
# workflow a read-only token and no secrets. The pull request's code (its
# install, the functions under test, pytest) only ever runs here. The card goes
# to the job summary and into the `numguard-result` artifact;
# numguard-comment.yml posts it on the pull request.
#
# Generated by `numguard init`. Pin the reusable workflow to a release tag or,
# stricter, to a full commit SHA, and keep `numguard-ref` the same.
name: numguard

on:
  pull_request:

permissions:
  contents: read

concurrency:
  group: numguard-${{{{ github.event.pull_request.number }}}}
  cancel-in-progress: true

jobs:
  check:
    uses: {prefix}/check.yml@{ref}
    with:
      numguard-ref: {ref}
      python-version: "3.12"
      # Installs the project under test; this runs PR code (unprivileged job).
      install-command: {_yaml_str(install)}
      config: numguard.toml   # read from the PR's base commit when it exists there
      fail-on: fail           # or "error" / "never"
"""


def comment_caller(ref: str) -> str:
    prefix = f"{TOOL_REPOSITORY}/.github/workflows"
    return f"""# numguard, part 2 of 2: post the card (PRIVILEGED, never runs PR code).
#
# Triggered when the `numguard` workflow completes. `workflow_run` runs with a
# token that can comment, so the reusable workflow never checks out, installs
# or executes anything from the pull request: it downloads the result
# artifact, validates it, re-renders the card, upserts one comment and sets a
# `numguard: pass|fail|error` label. Do not use `pull_request_target` instead.
#
# Generated by `numguard init`.
name: numguard comment

on:
  workflow_run:
    workflows: ["numguard"]   # must match the `name:` of numguard.yml
    types: [completed]

permissions: {{}}

jobs:
  comment:
    if: github.event.workflow_run.event == 'pull_request' && github.event.workflow_run.conclusion != 'cancelled'
    permissions:
      contents: read
      actions: read          # download the artifact of the triggering run
      pull-requests: write   # upsert the comment and the status label
    uses: {prefix}/comment.yml@{ref}
    with:
      numguard-ref: {ref}
      labels: true
"""


def agent_caller(ref: str, install: str = DEFAULT_INSTALL) -> str:
    prefix = f"{TOOL_REPOSITORY}/.github/workflows"
    return f"""# numguard suggested fixes (EXPERIMENTAL, opt-in).
#
# When the check run finds failing targets, an LLM proposes rewrites of the
# failing functions and numguard verifies each one by running the checks. The
# work is split over separate jobs (separate VMs):
#   gate    - decides whether to run; reads the API only, runs no PR code
#   propose - holds the LLM key; reads the PR as data, never installs or runs it
#   verify  - runs the rewrites against the checks; no secrets, read-only token
#   comment - re-posts the card with the suggested fixes; never runs PR code
#
# Setup: repository secret NUMGUARD_LLM_API_KEY, repository variables
# NUMGUARD_LLM_PROVIDER (anthropic | openai) and NUMGUARD_LLM_MODEL (optional:
# NUMGUARD_LLM_BASE_URL, and NUMGUARD_LLM_REASONING_EFFORT = none for OpenAI
# GPT-6 Luna), and `[agent] enabled = true` in numguard.toml. By default the
# agent only runs for pull requests by owners, members and collaborators, or
# labelled `numguard:agent`.
#
# Generated by `numguard init --agent`.
name: numguard agent

on:
  workflow_run:
    workflows: ["numguard"]   # must match the `name:` of numguard.yml
    types: [completed]

permissions: {{}}

jobs:
  agent:
    if: github.event.workflow_run.event == 'pull_request' && github.event.workflow_run.conclusion != 'cancelled'
    permissions:
      contents: read
      actions: read
      pull-requests: read
    uses: {prefix}/agent.yml@{ref}
    with:
      numguard-ref: {ref}
      llm-provider: ${{{{ vars.NUMGUARD_LLM_PROVIDER }}}}
      llm-model: ${{{{ vars.NUMGUARD_LLM_MODEL }}}}
      llm-base-url: ${{{{ vars.NUMGUARD_LLM_BASE_URL }}}}
      llm-reasoning-effort: ${{{{ vars.NUMGUARD_LLM_REASONING_EFFORT }}}}
      python-version: "3.12"
      install-command: {_yaml_str(install)}
      run-for: trusted   # or "everyone" (spends API credits on any fork PR)
    secrets:
      llm-api-key: ${{{{ secrets.NUMGUARD_LLM_API_KEY }}}}

  comment:
    needs: agent
    if: needs.agent.outputs.verified == 'true'
    permissions:
      contents: read
      actions: read
      pull-requests: write
    uses: {prefix}/comment.yml@{ref}
    with:
      numguard-ref: {ref}
      # Trusted values: the PR number comes from the gate job (API data, no PR
      # code ran there) and the artifact from this run's verify job.
      pr-number: ${{{{ needs.agent.outputs.pr-number }}}}
      artifact-run-id: ${{{{ github.run_id }}}}
      labels: true
"""


def config_template(agent: bool = False, targets: Sequence[str] = ()) -> str:
    text = f"""# numguard configuration (https://github.com/{TOOL_REPOSITORY}).
#
# `numguard check` (and the numguard GitHub workflow) runs every [[target]]
# below on numguard's edge-case catalogue: zeros, empty arrays, NaN, +-inf,
# huge/tiny/subnormal magnitudes, cancellation-prone data, several dtypes.
# In CI this file is read from the pull request's BASE commit, so a PR cannot
# weaken its own checks. Every key is documented in docs/CONFIG.md. Write
# targets by hand, or let the optional agent draft one for review:
#   numguard suggest mypkg.ops:logsumexp --write numguard.toml

# [defaults]                                # applied to every target
# dtypes = ["float32", "float64"]

# [[target]]
# name = "logsumexp"
# function = "mypkg.ops:logsumexp"          # or "path/to/file.py:logsumexp"
# inputs = ["any"]                          # one domain per positional argument
# properties = ["translation_equivariant"]
# reference = "special.logsumexp(x)"        # an expression over the argument names
# reference_precision = "float64"           # or "longdouble", or "mpmath" (elementwise)
# nan = "propagate"                         # NaN in -> NaN out
# allow_nonfinite = []                      # cases where inf/NaN is the right answer
# backend = "numpy"                         # or "torch", "jax", "cupy"

# [pytest]                                  # also run pytest (the numguard plugin is active)
# args = ["tests"]

# [agent]                                   # experimental suggested fixes (numguard-agent.yml)
# enabled = false
# rounds = 3                                # refinement rounds for local `numguard fix`
# max_targets = 3                           # failing targets per pull request
# timeout = 120                             # seconds per sandboxed check run
"""
    if agent:
        text = text.replace("# [agent]  ", "[agent]    ", 1).replace("# enabled = false\n# rounds",
                                                                     "enabled = true\n# rounds", 1)
    for t in targets:
        name = t.rpartition(":")[2].split(".")[-1]
        text += (f"\n[[target]]\nname = {json.dumps(name)}\nfunction = {json.dumps(t)}\n"
                 "# inputs = [\"any\"]\n# reference = \"...\"\n")
    return text


def init_repo(repo: str | Path = ".", *, agent: bool = False, force: bool = False, ref: str | None = None,
              install_command: str | None = None, targets: Sequence[str] = ()) -> InitResult:
    """Write the caller workflows and the config into ``repo``."""
    root = Path(repo)
    if not root.is_dir():
        raise InitError(f"not a directory: {root}")
    ref = ref or DEFAULT_REF
    if not _REF_RE.match(ref) or ".." in ref:
        raise InitError(f"invalid --ref {ref!r}: use a tag, branch or commit SHA")
    install = install_command or DEFAULT_INSTALL
    if "\n" in install or len(install) > 500:
        raise InitError("--install-command must be a single line")
    for t in targets:
        if not _TARGET_RE.match(t):
            raise InitError(f"invalid --target {t!r}: use 'package.module:function' or 'path/file.py:function'")
    files = {
        CHECK_PATH: check_caller(ref, install),
        COMMENT_PATH: comment_caller(ref),
        CONFIG_PATH: config_template(agent, targets),
    }
    if agent:
        files[AGENT_PATH] = agent_caller(ref, install)
    existing = [p for p in files if (root / p).exists()]
    if existing and not force:
        raise InitError("refusing to overwrite existing file(s): " + ", ".join(existing) + " (use --force)")
    for rel, text in files.items():
        target = root / rel
        if target.is_symlink():
            target.unlink()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    res = InitResult(written=list(files))
    if not targets:
        res.next_steps.append("Add [[target]] tables to numguard.toml (see the commented example), or draft one "
                              "with `numguard suggest MODULE:FUNC --write numguard.toml`; run `numguard check` "
                              "locally to try them.")
    res.next_steps.append("Review and commit the files: git add " + " ".join(files) + " && git commit -m 'Add numguard'")
    res.next_steps.append("Merge them to the default branch: workflow_run workflows (comment, agent) only run "
                          "from the default branch.")
    if agent:
        res.next_steps.append("Add the LLM key as a repository secret: gh secret set NUMGUARD_LLM_API_KEY")
        res.next_steps.append("Set repository variables: gh variable set NUMGUARD_LLM_PROVIDER --body anthropic "
                              "(or openai) and gh variable set NUMGUARD_LLM_MODEL --body <model id> (optional: "
                              "NUMGUARD_LLM_BASE_URL; for OpenAI GPT-6 Luna also NUMGUARD_LLM_REASONING_EFFORT=none)")
        res.next_steps.append("The agent runs for PRs by owners/members/collaborators, or when a maintainer adds the "
                              "`numguard:agent` label; set run-for: everyone to change that.")
    res.next_steps.append("Open a pull request: the card appears in the job summary and as a PR comment.")
    return res
